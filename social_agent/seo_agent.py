def render_markdown_article(topic: dict, date_str: str) -> str:
    """Format an article into the exact standard markdown expected by build_blog_pages.py."""
    lines = [
        f"id: {topic['id']}",
        f"slug: {topic['slug']}",
        f"title: {topic['title']}",
        f"h1: {topic['h1']}",
        f"description: {topic['description']}",
        f"category: {topic['category']}",
        f"keywords: {topic['keywords']}",
        f"banner: {topic['banner']}",
        f"banner_sub: {topic['banner_sub']}",
        f"date: {date_str}",
        f"snippet: {topic['snippet']}",
        f"glyph: {topic.get('glyph', 'ॐ')}",
        f"motif: {topic.get('motif', 'wheel')}",
        f"palette: {topic.get('palette', 'saffron')}",
        ""
    ]
    
    # Sections
    for heading, text in topic["body_sections"]:
        lines.append(f"## {heading}")
        lines.append("")
        lines.append(text)
        lines.append("")
        
    # FAQs
    lines.append("## पूछे जाने वाले प्रश्न")
    lines.append("")
    for q, a in topic["faqs"]:
        lines.append(f"Q: {q}")
        lines.append(f"A: {a}")
        
    return "\n".join(lines)


def ping_indexnow(urls: list) -> bool:
    """Send IndexNow ping to search engines for immediate crawling."""
    if not urls:
        return False
        
    payload = {
        "host": "shriramjiastro.in",
        "key": INDEXNOW_KEY,
        "keyLocation": f"https://shriramjiastro.in/{INDEXNOW_KEY}.txt",
        "urlList": urls
    }
    
    req = urllib.request.Request(
        "https://api.indexnow.org/indexnow",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json; charset=utf-8"},
        method="POST"
    )
    
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            print(f"[SEO Agent] IndexNow ping response: {resp.status} {resp.reason}")
            return resp.status in (200, 202)
    except Exception as e:
        print(f"[SEO Agent] IndexNow ping notice: {e}")
        return False


def run_daily_seo(target_date: datetime.date = None) -> dict:
    """
    Main entry point:
    1. Checks if today's article already exists.
    2. If not, picks next topic from curated BPHS queue.
    3. Renders banner, builds HTML, updates sitemap and rss.xml.
    4. Pings IndexNow.
    5. Commits and pushes to GitHub main.
    """
    if not target_date:
        target_date = datetime.date.today()
        
    date_str = target_date.isoformat()
    print(f"\n=======================================================")
    print(f"📈 SRA AUTONOMOUS SEO AGENT - DAILY ARTICLE ({date_str})")
    print(f"=======================================================")
    
    existing_files = list(BLOG_SEO_DIR.glob("*.md"))
    existing_slugs = {f.stem for f in existing_files}
    
    # Check if an article was already created for this exact date
    date_matched = None
    for f in existing_files:
        try:
            head = f.read_text(encoding="utf-8").split("\n\n", 1)[0]
            for line in head.splitlines():
                if line.startswith("date: ") and line.split(": ", 1)[1].strip() == date_str:
                    date_matched = f.stem
                    break
        except Exception:
            pass
        if date_matched:
            break
            
    if date_matched:
        print(f"[SEO Agent] Article for {date_str} already published: {date_matched}.html")
        article_url = f"https://shriramjiastro.in/blog/{date_matched}.html"
        return {"status": "already_published", "slug": date_matched, "url": article_url}
        
    # Find next unwritten topic
    next_topic = None
    for cand in PLANNED_TOPICS:
        if cand["slug"] not in existing_slugs:
            next_topic = cand
            break
            
    if not next_topic:
        print("[SEO Agent] All planned topics are published! Queue exhausted.")
        return {"status": "queue_exhausted"}
        
    slug = next_topic["slug"]
    print(f"[SEO Agent] Selected topic: {next_topic['title']} ({slug})")
    
    # 1. Write markdown article
    md_content = render_markdown_article(next_topic, date_str)
    md_file = BLOG_SEO_DIR / f"{slug}.md"
    md_file.write_text(md_content, encoding="utf-8")
    print(f"[SEO Agent] Wrote markdown: {md_file.name}")
    
    # 2. Render Retina OG Banner (1200x630)
    print(f"[SEO Agent] Rendering OG retina banner for {slug}...")
    try:
        subprocess.run(
            [sys.executable, str(ROOT_DIR / "tools" / "render_blog_banners.py"), slug],
            cwd=str(ROOT_DIR),
            check=True,
            capture_output=True
        )
        print(f"[SEO Agent] Successfully generated assets/blog-og/{slug}.jpg")
    except Exception as e:
        print(f"[SEO Agent] Banner render notice: {e}")
        
    # 3. Compile static HTML pages, update blogs.html, sitemap.xml, and rss.xml
    print(f"[SEO Agent] Compiling HTML pages & refreshing sitemap/RSS...")
    try:
        subprocess.run(
            [sys.executable, str(ROOT_DIR / "tools" / "build_blog_pages.py")],
            cwd=str(ROOT_DIR),
            check=True
        )
        print(f"[SEO Agent] Successfully built blog/{slug}.html & updated sitemap.xml / rss.xml")
    except Exception as e:
        print(f"[SEO Agent] Error building blog pages: {e}")
        return {"status": "build_error", "error": str(e)}
        
    article_url = f"https://shriramjiastro.in/blog/{slug}.html"
    
    # 4. Ping IndexNow
    print(f"[SEO Agent] Pinging IndexNow for {article_url}...")
    ping_indexnow([
        article_url,
        "https://shriramjiastro.in/blogs.html",
        "https://shriramjiastro.in/sitemap.xml",
        "https://shriramjiastro.in/rss.xml"
    ])
    
    # 5. Git Commit & Push for instant Render live deployment
    print(f"[SEO Agent] Committing and pushing to origin main...")
    try:
        subprocess.run(
            ["git", "add", "blog/", "assets/blog-og/", "data/blog_seo/", "blogs.html", "sitemap.xml", "rss.xml"],
            cwd=str(ROOT_DIR),
            check=True
        )
        subprocess.run(
            ["git", "commit", "-m", f"feat(seo): auto-publish daily classical article '{next_topic['title'][:60]}'"],
            cwd=str(ROOT_DIR),
            check=True
        )
        subprocess.run(
            ["git", "push", "origin", "main"],
            cwd=str(ROOT_DIR),
            check=True
        )
        print(f"[SEO Agent] ✅ Successfully pushed to GitHub main! Live on Render in ~2 mins.")
    except Exception as e:
        print(f"[SEO Agent] Git push notice: {e}")
        
    return {
        "status": "published",
        "slug": slug,
        "title": next_topic["title"],
        "url": article_url
    }


